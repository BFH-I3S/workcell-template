#!/usr/bin/env python3
"""
Generate a cell's MoveIt and ros2_control configuration from its composition.

Reads src/<package>/cells/<cell>.yaml and the module descriptors in
src/cell_description/modules/, and writes, per variant, into
src/<package>/cells/<cell>/<variant>/:

  robot.srdf               groups, named states, end effector, virtual joint,
                           links whose collision geometry a module replaces,
                           and the disabled collisions (MoveIt's
                           collisions_updater on the expanded URDF, as the
                           Setup Assistant computes them)
  kinematics.yaml          IK solver per group
  joint_limits.yaml        the modules' limits merged with the cell's
  moveit_controllers.yaml  what move_group executes on
  ros2_controllers.yaml    controller-manager parameters (variants that start
                           their own manager, i.e. simulations); paths are
                           $(find-pkg-share ...) tokens, resolved at launch by
                           cell_description.composition.controller_manager_params

The descriptions the cells name must be built and installed (colcon build),
since the URDF is expanded from the install space. Rebuild cell_description
afterwards so the launch files see the new files.

Usage (from the workspace root, ROS and install/ sourced):
    python3 tools/generate_cell.py                   every cell
    python3 tools/generate_cell.py gantry --variant sim
    python3 tools/generate_cell.py --check           exit 1 if a generated file
                                                     is stale (collisions aside)
"""

import argparse
import difflib
import os
import re
import subprocess
import sys
import tempfile
import xml.dom.minidom
import xml.etree.ElementTree as ET

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CELL_DIR = os.path.join(ROOT, "src", "cell_description")
sys.path.insert(0, CELL_DIR)
from cell_description import composition  # noqa: E402  (the source tree's, not the installed copy)


def header(cell, comment):
    modules = sorted({m["type"] for m in cell.modules.values()})
    lines = [f"Generated by tools/generate_cell.py from cells/{cell.name}.yaml and",
             "modules/" + ", modules/".join(f"{m}.yaml" for m in modules) + ".",
             "Do not edit: change those and regenerate."]
    return "\n".join(f"{comment} {line}" for line in lines) + "\n"


def dump_yaml(cell, data):
    return header(cell, "#") + yaml.safe_dump(data, sort_keys=False, default_flow_style=False, width=100)


def expand_urdf(variant, out_dir):
    ref = variant.urdf
    args = [f"{k}:={v}" for k, v in (ref.get("args") or {}).items()]
    result = subprocess.run(["xacro", composition.ref_path(ref), *args], capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(f"xacro {composition.ref_path(ref)} failed: {result.stderr.strip()[:400]}")
    path = os.path.join(out_dir, f"{variant.cell.name}_{variant.name}.urdf")
    with open(path, "w") as handle:
        handle.write(result.stdout)
    return path, ET.parse(path).getroot().get("name")


def disabled_collisions(urdf_path, srdf_path, out_dir, trials, timeout=None):
    out = srdf_path + ".collisions"
    result = subprocess.run(
        ["ros2", "run", "moveit_setup_assistant", "collisions_updater", "--urdf", urdf_path,
         "--srdf", srdf_path, "--output", out, "--default", "--always",
         "--trials", str(trials), "--min-collision-fraction", "0.95"],
        capture_output=True, text=True, timeout=timeout or None)
    if result.returncode != 0 or not os.path.isfile(out):
        raise RuntimeError(f"collisions_updater failed: {result.stderr.strip()[-400:]}")
    pairs = {}
    for element in ET.parse(out).getroot().findall("disable_collisions"):
        a, b = sorted((element.get("link1"), element.get("link2")))
        pairs[(a, b)] = element.get("reason")
    return pairs


def render_srdf(cell, robot, pairs):
    for (a, b), reason in sorted(pairs.items()):
        ET.SubElement(robot, "disable_collisions", link1=a, link2=b, reason=reason)
    text = xml.dom.minidom.parseString(ET.tostring(robot)).toprettyxml(indent="  ")
    text = text.split("\n", 1)[1]           # minidom's own declaration
    comment = header(cell, "").replace("\n ", "\n  ").strip()
    note = ("Disabled collisions: MoveIt's collisions_updater (Setup Assistant\n"
            "  sampler): Adjacent = joined by a joint, Default = touching in the zero\n"
            "  state, Always = touching in almost every sampled state, Never = never\n"
            "  touching in any sampled state (only saves collision checks).")
    return f'<?xml version="1.0"?>\n<!--\n  {comment}\n\n  {note}\n-->\n{text}'


def srdf_without_collisions(text):
    return re.sub(r"\s*<disable_collisions [^>]*/>", "", text)


def generate(cell, variant, trials, check, tmp, timeout=None):
    """{filename: content} for one variant."""
    problems = variant.module_problems()
    if problems:
        raise SystemExit(f"{variant.where}: module capabilities are invalid: " + "; ".join(problems))
    urdf_path, robot_name = expand_urdf(variant, tmp)
    links = [link.get("name") for link in ET.parse(urdf_path).getroot().findall("link")]
    robot = variant.srdf_without_collisions(robot_name, links)
    base = os.path.join(tmp, f"{cell.name}_{variant.name}.srdf")
    ET.ElementTree(robot).write(base)
    pairs = {} if check else disabled_collisions(urdf_path, base, tmp, trials, timeout)
    checked = sorted(p for p, r in pairs.items() if r == "Default" and p in variant.checked_pairs())
    kept = sorted(p for p, r in pairs.items() if r == "Never" and variant.kept(*p))
    for pair in checked + kept:
        del pairs[pair]
    files = {
        "robot.srdf": render_srdf(cell, robot, pairs),
        "kinematics.yaml": dump_yaml(cell, variant.kinematics()),
        "joint_limits.yaml": dump_yaml(cell, variant.joint_limits()),
        "moveit_controllers.yaml": dump_yaml(cell, variant.moveit_controllers()),
    }
    controllers = variant.ros2_controllers()
    if controllers is not None:
        files["ros2_controllers.yaml"] = dump_yaml(cell, controllers)
    if not check:
        reasons = {}
        for reason in pairs.values():
            reasons[reason] = reasons.get(reason, 0) + 1
        print(f"  {variant.where}: {len(pairs)} disabled pairs {reasons}")
        if kept:
            print(f"  {variant.where}: kept checked (keep_collisions, sampled Never): {kept}")
        touching_kept = sorted(p for p, r in pairs.items() if r != "Never" and variant.kept(*p))
        if touching_kept:
            print(f"  {variant.where}: keep_collisions matches pairs that touch or are adjacent, "
                  f"left disabled: {touching_kept}")
        default = sorted(p for p, r in pairs.items() if r == "Default")
        if default:
            print(f"  {variant.where}: touching in the zero state, review: {default}")
        if checked:
            print(f"  {variant.where}: touching in the zero state, kept checked (collisions.checked): {checked}")
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("cells", nargs="*", help="cells to generate (default: all)")
    parser.add_argument("--variant", help="only this variant")
    # 10000 (the Setup Assistant's default) let pairs that touch only in rare
    # poses come out "Never" by chance: narrowing the UR joints to their soft
    # limits (20 Oct 2026) disabled the gantry motor against the gripper and
    # the wrist camera. 100000 found both colliding, and takes a few seconds on
    # a desktop; the gantry's real variant with fingertip pads took over 30 min
    # on the Jetson (2 Nov 2026), hence no time limit by default.
    parser.add_argument("--trials", type=int, default=100000,
                        help="collisions_updater samples for never-colliding pairs (default 100000)")
    parser.add_argument("--timeout", type=float, default=0,
                        help="seconds collisions_updater may take, 0 = no limit (default)")
    parser.add_argument("--check", action="store_true",
                        help="compare with the files on disk instead of writing (disabled collisions excluded)")
    args = parser.parse_args()

    stale = 0
    with tempfile.TemporaryDirectory(prefix="generate_cell_") as tmp:
        for name in args.cells or composition.list_cells(CELL_DIR):
            cell = composition.Cell(name, CELL_DIR)
            for variant_name in cell.variant_names():
                if args.variant and variant_name != args.variant:
                    continue
                variant = cell.variant(variant_name)
                files = generate(cell, variant, args.trials, args.check, tmp, args.timeout)
                out_dir = variant.generated_dir()
                os.makedirs(out_dir, exist_ok=True)
                for filename in composition.GENERATED_FILES:
                    path = os.path.join(out_dir, filename)
                    if args.check:
                        have = open(path).read() if os.path.isfile(path) else None
                        want = files.get(filename)
                        if filename == "robot.srdf" and have is not None:
                            have, want = srdf_without_collisions(have), srdf_without_collisions(want)
                        if have != want:
                            stale += 1
                            print(f"STALE  {variant.where}/{filename}")
                            if have and want:
                                sys.stdout.writelines(list(difflib.unified_diff(
                                    have.splitlines(True), want.splitlines(True), "on disk", "generated", n=1))[:40])
                        continue
                    if filename in files:
                        with open(path, "w") as handle:
                            handle.write(files[filename])
                    elif os.path.isfile(path):
                        os.remove(path)
                if not args.check:
                    print(f"wrote {os.path.relpath(out_dir, ROOT)}/ ({', '.join(files)})")
    if args.check:
        print(f"{stale} stale file(s)" if stale else "generated files are up to date")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
